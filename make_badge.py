#!/usr/bin/env python3
"""Draws the name badge from a theme's "badge" block and writes it where the mod reads it.

    python3 make_badge.py lab37-cyberpunk                 # name and sub from the theme
    python3 make_badge.py my-brand --name ALEX --sub "ACME" --out ~/somewhere/skin-badge

Writes <out>/hooks/badge.ts (the mod imports it; default out: plugins/skin-badge, the committed
default badge) and preview/badge.svg (to look at). install.sh points --out at its own copy of the mod.
Flat and sharp: no gradient, no glow. Optional chamfered corner and an offset outline
behind the hairline, set per theme.
"""
import argparse, json, sys
from pathlib import Path
from xml.sax.saxutils import escape

HERE = Path(__file__).parent
THEMES = HERE / "themes"


def badge(name: str, sub: str, b: dict, font: str, mono: bool) -> tuple[str, int, int]:
    h, pad = 28, 12
    cut = 8 if b.get("chamfer") else 0
    adv = 0.6 if mono else 0.66  # caps advance per em; sans caps run wider
    name_w = round(len(name) * 13 * (adv + 0.12))  # + letter-spacing
    sub_w = round(len(sub) * 9 * (adv + 0.16))
    w = pad + 8 + 8 + name_w + 12 + sub_w + pad
    # half-pixel offsets keep the 1px hairlines crisp
    edge = lambda dx, dy: (f"M{0.5 + dx} {0.5 + dy}H{w - cut - 0.5 + dx}L{w - 0.5 + dx} {cut + 0.5 + dy}"
                           f"V{h - 0.5 + dy}H{0.5 + dx}Z")
    my = h / 2 - 4
    if b.get("markShape") == "window":  # a framed square split in four panes
        mark = (f'<rect x="{pad + 0.5}" y="{my + 0.5}" width="7" height="7" fill="none" stroke="{b["mark"]}"/>'
                f'<path d="M{pad + 4} {my}V{my + 8}M{pad} {my + 4}H{pad + 8}" stroke="{b["mark"]}"/>')
    else:
        mark = f'<rect x="{pad}" y="{my + 0.5}" width="7" height="7" fill="{b["mark"]}"/>'
    x_name = pad + 8 + 8
    x_sub = x_name + name_w + 12
    svg = (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{w + 2}" height="{h + 2}" viewBox="0 0 {w + 2} {h + 2}">'
        + (f'<path d="{edge(2, 2)}" fill="none" stroke="{b["offset"]}" stroke-opacity=".7"/>' if b.get("offset") else "")
        + f'<path d="{edge(0, 0)}" fill="{b["fill"]}" stroke="{b["stroke"]}"/>{mark}'
        f'<text x="{x_name}" y="{h / 2 + 4.5}" font-family="{escape(font)}" font-size="13" font-weight="700" '
        f'letter-spacing="1.5" fill="{b["ink"]}">{escape(name)}</text>'
        f'<text x="{x_sub}" y="{h / 2 + 3}" font-family="{escape(font)}" font-size="9" font-weight="500" '
        f'letter-spacing="1.4" fill="{b["subInk"]}">{escape(sub)}</text>'
        "</svg>"
    )
    return svg, w + 2, h + 2


def badge_text(theme: dict, name: str | None = None, sub: str | None = None) -> tuple[str, str, str, bool]:
    """The badge's name, sub-label, font stack and whether it is mono, as installed; preview.py uses it too."""
    b, fonts = theme["badge"], theme.get("fonts", {})
    name = (name or b["name"]).strip().upper()
    sub = (sub if sub is not None else b.get("sub", "")).strip().upper()
    assert 0 < len(name) <= 24 and len(sub) <= 12, "badge text too long for the band"
    mono = bool(fonts.get("mono"))
    font = (f"'{fonts['mono']}','SF Mono',ui-monospace,Menlo,monospace" if mono
            else f"'{fonts.get('sans', 'system-ui')}',system-ui,sans-serif")
    return name, sub, font, mono


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("theme", help="a name in themes/, e.g. lab37-cyberpunk")
    ap.add_argument("--name")
    ap.add_argument("--sub")
    ap.add_argument("--out", type=Path, default=HERE / "plugins/skin-badge", help="the skin-badge mod folder to write into")
    a = ap.parse_args()
    if not (a.out / "hooks").is_dir(): sys.exit(f"{a.out} is not a skin-badge mod folder (no hooks/)")
    if not (THEMES / f"{a.theme}.json").exists(): sys.exit(f"no themes/{a.theme}.json")
    theme = json.loads((THEMES / f"{a.theme}.json").read_text())
    b = theme["badge"]
    name, sub, font, mono = badge_text(theme, a.name, a.sub)
    svg, w, h = badge(name, sub, b, font, mono)
    assert svg.startswith("<svg") and len(svg) < 131072 and "<script" not in svg
    (HERE / "preview").mkdir(exist_ok=True)
    (HERE / "preview" / "badge.svg").write_text(svg)
    (a.out / "hooks" / "badge.ts").write_text(
        "// Generated by make_badge.py; edit there, not here.\n"
        f"export const BADGE_NAME = {json.dumps(name)}\n"
        f"export const BADGE_SUB = {json.dumps(sub)}\n"
        f"export const BADGE_WIDTH = {w}\n"
        f"export const BADGE_HEIGHT = {h}\n"
        f"export const BADGE_INK = {json.dumps(b['ink'])}\n"
        f"export const BADGE_MARK = {json.dumps(b['mark'])}\n"
        f"export const BADGE_SVG = {json.dumps(svg)}\n"
    )
    print(f"badge {name} / {sub}: {w}x{h}px -> {a.out}/hooks/badge.ts, preview/badge.svg")


if __name__ == "__main__":
    main()
